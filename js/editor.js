(() => {
  'use strict';
  const CAMS = window.CAMERAS;
  const U = window.CCTV;
  const W = 1280, H = 720;
  const LS_KEY = 'cctv-anomaly-editor-v1';
  const $ = (id) => document.getElementById(id);
  const canvas = $('edCanvas'), ctx = canvas.getContext('2d');

  // ---------- Data ----------
  function fromFile() {
    const d = {};
    CAMS.forEach((c) => { d[c.id] = U.getEntries(c.id, window.ANOMALY_DATA); });
    return d;
  }
  let data;
  try { data = JSON.parse(localStorage.getItem(LS_KEY)) || fromFile(); } catch { data = fromFile(); }
  CAMS.forEach((c) => { if (!data[c.id]) data[c.id] = U.defaultEntries(); });

  let camId = CAMS[0].id;
  let idx = 0;
  const entries = () => data[camId];
  const entry = () => entries()[idx];

  function save() {
    localStorage.setItem(LS_KEY, JSON.stringify(data));
    $('edOut').value = exportText();
    renderThumbs();
    renderSummary();
  }

  function exportText() {
    const lines = ['// Generated by editor.html', 'window.ANOMALY_DATA = {'];
    CAMS.forEach((c) => {
      lines.push(`  "${c.id}": [ // ${c.label} ${c.name}`);
      data[c.id].forEach((e) => lines.push(`    ${JSON.stringify({ num: e.num, anomaly: e.anomaly })},`));
      lines.push('  ],');
    });
    lines.push('};', '');
    return lines.join('\n');
  }

  // ---------- UI ----------
  const sel = $('edCam');
  CAMS.forEach((c) => {
    const o = document.createElement('option');
    o.value = c.id; o.textContent = `${c.label} — ${c.name}`;
    sel.appendChild(o);
  });
  sel.onchange = () => { camId = sel.value; idx = 0; renderThumbs(); render(); };

  function renderThumbs() {
    const box = $('thumbs');
    box.innerHTML = '';
    entries().forEach((e, i) => {
      const t = document.createElement('div');
      t.className = 'thumb' + (i === idx ? ' sel' : '');
      const res = U.getLoaded(camId, e.num);
      if (res) t.style.backgroundImage = `url("${res.src}")`;
      else if (res === null) t.classList.add('missing');
      t.innerHTML = `<span class="lbl">${e.num}${res === null ? ' (missing)' : ''}</span><span class="tag ${e.anomaly ? 'A' : 'N'}">${e.anomaly ? 'A' : 'N'}</span>`;
      t.onclick = () => { idx = i; renderThumbs(); render(); };
      box.appendChild(t);
    });
  }

  function renderSummary() {
    $('edSummary').innerHTML = CAMS.map((c) => {
      const a = data[c.id].filter((e) => e.anomaly).length;
      return `${c.label}: ${a} anomaly / ${data[c.id].length - a} normal`;
    }).join('<br>');
  }

  function render() {
    const cam = CAMS.find((c) => c.id === camId);
    const camIndex = CAMS.indexOf(cam);
    const e = entry();
    const res = U.getLoaded(camId, e.num);
    if (res) ctx.drawImage(res.img, 0, 0, W, H);
    else U.drawPlaceholder(ctx, W, H, camIndex, cam, { num: e.num, anomaly: null });
    if (e.anomaly) {
      const { x, y, r } = e.anomaly;
      ctx.strokeStyle = '#ff2a2a'; ctx.lineWidth = 4; ctx.shadowColor = '#ff0000'; ctx.shadowBlur = 8;
      ctx.beginPath(); ctx.arc(x * W, y * H, r * W, 0, Math.PI * 2); ctx.stroke();
      ctx.shadowBlur = 0;
      ctx.fillStyle = '#ff2a2a';
      ctx.beginPath(); ctx.arc(x * W, y * H, 3, 0, Math.PI * 2); ctx.fill();
    }
    $('edTitle').textContent = `${cam.label} ${cam.name} — image ${e.num}`;
    $('edInfo').innerHTML = `
      File: <b>${res ? res.src : res === null ? `assets/${camId}/${e.num}.* (missing)` : 'loading...'}</b><br>
      Type: <b style="color:${e.anomaly ? 'var(--red)' : 'var(--accent)'}">${e.anomaly ? 'ANOMALY' : 'NORMAL'}</b><br>
      ${e.anomaly ? `x ${e.anomaly.x} · y ${e.anomaly.y} · r ${e.anomaly.r}` : ''}`;
  }

  // ---------- Drawing ----------
  let dragStart = null;
  const toCanvas = (ev) => {
    const r = canvas.getBoundingClientRect();
    return { x: ((ev.clientX - r.left) / r.width) * W, y: ((ev.clientY - r.top) / r.height) * H };
  };
  const round = (v) => Math.round(v * 10000) / 10000;
  function setCircle(cx, cy, rpx) {
    entry().anomaly = { x: round(cx / W), y: round(cy / H), r: round(Math.max(rpx, 10) / W) };
  }
  canvas.addEventListener('pointerdown', (ev) => {
    canvas.setPointerCapture(ev.pointerId);
    dragStart = toCanvas(ev);
    setCircle(dragStart.x, dragStart.y, 0.05 * W);
    render();
  });
  canvas.addEventListener('pointermove', (ev) => {
    if (!dragStart) return;
    const p = toCanvas(ev);
    const d = Math.hypot(p.x - dragStart.x, p.y - dragStart.y);
    if (d > 6) { setCircle(dragStart.x, dragStart.y, d); render(); }
  });
  canvas.addEventListener('pointerup', () => { if (dragStart) { dragStart = null; save(); } });

  const go = (d) => { idx = (idx + d + entries().length) % entries().length; renderThumbs(); render(); };
  const markNormal = () => { entry().anomaly = null; save(); render(); };
  $('edPrev').onclick = () => go(-1);
  $('edNext').onclick = () => go(1);
  $('edNormal').onclick = markNormal;
  window.addEventListener('keydown', (e) => {
    if (e.target.tagName === 'TEXTAREA' || e.target.tagName === 'SELECT') return;
    if (e.key === 'ArrowRight') go(1);
    else if (e.key === 'ArrowLeft') go(-1);
    else if (e.key === 'n' || e.key === 'N' || e.key === 'Delete') markNormal();
  });

  $('edDownload').onclick = () => {
    const blob = new Blob([exportText()], { type: 'text/javascript' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob); a.download = 'anomalies.js'; a.click();
    URL.revokeObjectURL(a.href);
  };
  $('edCopy').onclick = async () => {
    try { await navigator.clipboard.writeText(exportText()); $('edCopy').textContent = 'Copied!'; }
    catch { $('edOut').select(); document.execCommand('copy'); $('edCopy').textContent = 'Copied!'; }
    setTimeout(() => { $('edCopy').textContent = 'Copy'; }, 1200);
  };
  $('edReset').onclick = () => {
    if (!confirm('Discard editor changes and reload from js/anomalies.js?')) return;
    localStorage.removeItem(LS_KEY);
    data = fromFile();
    save(); render();
  };

  // ---------- Boot ----------
  save();
  render();
  CAMS.forEach((c) => data[c.id].forEach((e) => U.loadImage(c.id, e.num).then(() => {
    if (c.id === camId) { renderThumbs(); if (e === entry()) render(); }
  })));
})();
